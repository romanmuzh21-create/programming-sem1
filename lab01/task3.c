#include <stdio.h>

int main(void) {
    double rho, h;
    const double g = 9.81;

    printf("Розрахунок гідростатичного тиску стовпа рідини \n");
    printf("Введіть густину рідини rho (кг/м^3): ");
    if (scanf("%lf", &rho) != 1 || rho <= 0) {
        printf("Помилка: некоректне значення густини (має бути число > 0).\n");
        return 1;
    }

    printf("Введіть глибину h (м): ");
    if (scanf("%lf", &h) != 1 || h < 0) {
        printf("Помилка: некоректне значення глибини (має бути число >= 0).\n");
        return 1;
    }

    double P = rho * g * h;

    printf("\n Результат \n");
    printf("Гідростатичний тиск P = %.2f Па (Паскаль)\n", P);
    printf("Гідростатичний тиск P = %.3f кПа (кілопаскаль)\n", P / 1000.0);

    return 0;
}
